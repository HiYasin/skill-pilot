export const SUPPORTED_CHARACTERS = Object.keys(GLYPHS);

const GAP = 1;

/** Turn text into 7 pixel rows (strings of "#" and "."). Unknown characters render as a space. */
export function pixelRows(text: string): string[] {
  const rows = ["", "", "", "", "", "", ""];
  const chars = [...text.toUpperCase()];
  chars.forEach((ch, i) => {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "];
    for (let r = 0; r < 7; r++) rows[r] += glyph[r] + (i < chars.length - 1 ? ".".repeat(GAP) : "");
  });
  return rows;
}

/** The wordmark as 4 terminal lines built from half blocks. */
export function renderWordmark(text: string): string[] {
  const rows = [...pixelRows(text), ""];
  const width = rows[0].length;
  rows[7] = ".".repeat(width);
  const lines: string[] = [];
  for (let r = 0; r < 8; r += 2) {
    let line = "";
    for (let c = 0; c < width; c++) {
      const top = rows[r][c] === "#";
      const bottom = rows[r + 1][c] === "#";
      line += top && bottom ? "█" : top ? "▀" : bottom ? "▄" : " ";
    }
    lines.push(line);
  }
  return lines;
}
